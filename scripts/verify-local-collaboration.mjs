import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
// Functional smoke check in a new, disposable browser profile on the development preview.
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
await context.route('https://**/*',route=>route.abort());
const page=await context.newPage(),checks=[];
const pass=message=>{checks.push(message);console.log('PASS:',message);};
const modal=()=>page.getByRole('dialog');
try{
  await page.goto('http://127.0.0.1:5173/questions?preview=1');
  await expect(page.locator('.preview-bar')).toBeVisible();
  await page.locator('.qh-actions .button.primary').click();
  await modal().locator('textarea').first().fill('Local UX check: confirm the delivery owner?');
  await modal().getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(modal()).toHaveCount(0);
  const card=page.locator('.inline-question').filter({hasText:'Local UX check: confirm the delivery owner?'});
  await expect(card).toBeVisible();
  pass('A new general question is created and opened for discussion.');
  await card.getByLabel('Your reply',{exact:false}).fill('Local test reply: the project lead confirms ownership.');
  await card.getByRole('button',{name:'Post reply',exact:true}).click();
  await expect(card.locator('.reply-card')).toContainText('the project lead confirms ownership');
  await card.getByRole('button',{name:'Accept this reply',exact:true}).click();
  await expect(card.locator('.reply-card')).toHaveClass(/is-accepted/);
  pass('A separate reply saves and the asker can accept it.');
  await page.reload();
  await expect(page.locator('.reply-card.is-accepted')).toBeVisible();
  await page.getByRole('button',{name:'Reopen question',exact:true}).click();
  await expect(page.locator('.reply-card.is-accepted')).toHaveCount(0);
  pass('Reply acceptance persists and can be reopened.');
  await page.locator('.inline-question-badges button').first().click();
  await modal().getByLabel('Question scope',{exact:true}).selectOption('FN-BKG-01');
  await modal().getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(card.locator('.question-scope-line')).toContainText('FN-BKG-01');
  await expect(card.locator('.reply-card')).toHaveCount(1);
  pass('Moving scope preserves the question ID and its replies.');
  await page.locator('.inline-question-badges .delete-button').click();
  await modal().getByRole('button',{name:'Delete',exact:true}).click();
  await expect(card).toHaveCount(0);
  await page.goto('http://127.0.0.1:5173/activity?preview=1&view=trash');
  await page.locator('.trash-card').filter({hasText:'Local UX check'}).getByRole('button',{name:'Restore item',exact:true}).click();
  await modal().getByRole('button',{name:'Restore item',exact:true}).click();
  await expect(modal()).toHaveCount(0);
  await expect(page.locator('.trash-card').filter({hasText:'Local UX check'})).toHaveCount(0);
  await page.goto('http://127.0.0.1:5173/questions?preview=1&q=Local+UX+check&view=expanded');
  await expect(page.locator('.inline-question')).toContainText('Local UX check');
  await expect(page.locator('.reply-card')).toHaveCount(1);
  pass('Delete and controlled restoration preserve the discussion in local preview.');
  await page.goto('http://127.0.0.1:5173/requirements?preview=1&module=B&sort=id');
  await expect(page.locator('.requirement-summary-row')).toHaveCount(11);
  await page.locator('.requirement-id').filter({hasText:'REG-DAC-01'}).first().click();
  await expect(page.locator('.detail-navigation')).toBeVisible();
  await page.locator('.detail-navigation>a').click();
  await expect(page).toHaveURL(/module=B/);
  await expect(page).toHaveURL(/sort=id/);
  await expect(page.locator('.requirement-summary-row')).toHaveCount(11);
  pass('Returning from detail retains the matrix filter and sort.');
  await page.goto('http://127.0.0.1:5173/requirements?preview=1&open=FN-BKG-01');
  await page.locator('.inline-question-composer textarea').first().fill('Unsent local draft that must survive navigation.');
  await page.locator('.sidebar a[href="/questions"]').click();
  await page.locator('.sidebar a[href="/requirements"]').click();
  await page.locator('[data-requirement-id="FN-BKG-01"] .requirement-expand').click();
  await expect(page.locator('.inline-question-composer textarea').first()).toHaveValue('Unsent local draft that must survive navigation.');
  await page.reload();
  await expect(page.locator('.inline-question-composer textarea').first()).toHaveValue('Unsent local draft that must survive navigation.');
  pass('Unsent drafts survive SPA navigation and a full page reload.');
  await page.goto('http://127.0.0.1:5173/sources?preview=1');
  await page.locator('.decision-register .section-heading .button').click();
  await modal().locator('textarea').first().fill('Local proposed scope decision');
  await modal().getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.locator('.decision-card')).toContainText('Local proposed scope decision');
  await expect(page.locator('.decision-card')).toContainText('Proposed');
  pass('A new decision is proposed, not silently confirmed.');
  await page.locator('.decision-card button').first().click();
  await modal().getByLabel('Status',{exact:true}).selectOption('confirmed');
  await modal().getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(modal().getByRole('alert')).toContainText('Confirmation evidence is required');
  await modal().getByLabel('Source / evidence reference',{exact:true}).fill('Synthetic meeting reference for this local test only.');
  await modal().getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(modal()).toHaveCount(0);
  await expect(page.locator('.decision-card')).toContainText('Confirmed');
  pass('Decision confirmation requires evidence and shows recorded confirmation.');
  await page.goto('http://127.0.0.1:5173/review-packs?preview=1');
  await page.locator('.ai-check').filter({hasText:'Include recorded decisions'}).locator('input').check();
  await expect(page.locator('.ai-context-preview')).toContainText('Local proposed scope decision');
  pass('Recorded decisions enter the review pack only after explicit selection.');
  await mkdir('.backups/uiux-remediation-20260929',{recursive:true});
  await writeFile('.backups/uiux-remediation-20260929/local-functional-smoke.json',JSON.stringify({environment:'Disposable loopback preview; external requests blocked',checks,passed:true},null,2));
}finally{
  await context.close();
  await browser.close();
}
